#!/bin/bash
#
# setup-macos-docker.sh
#
# Makes the ISOTROPY suite (findsym, smodes, iso, comsubs) runnable on macOS.
#
# WHY THIS EXISTS
# ---------------
# BYU distributes the ISOTROPY command-line suite as prebuilt Linux x86-64
# binaries only. There is no macOS build. On an Apple Silicon Mac that is two
# incompatibilities stacked: wrong OS and wrong CPU architecture. Running the
# binaries directly gives "exec format error".
#
# This script installs small shell wrappers into ~/.local/bin that run the real
# Linux binaries inside a Docker container (x86-64 emulated via Rosetta), so
# that `findsym foo.in` just works from a normal macOS shell. Anything calling
# these programs -- including smodes_phonons itself -- does not need to know
# Docker is involved.
#
# This is a DEVELOPER CONVENIENCE for macOS only. Linux users (including HPC
# clusters) run the binaries natively and never need this.
#
# PREREQUISITES
# -------------
#   1. Docker Desktop installed and running.
#      Settings -> General -> "Use Rosetta for x86_64/amd64 emulation" enabled.
#   2. The ISOTROPY suite unzipped somewhere (see ISOBYU_DIR below).
#      Download iso.zip from https://iso.byu.edu/iso/isolinux.php
#   3. ~/.local/bin on your PATH. If not, add to ~/.zshrc:
#        export PATH="$HOME/.local/bin:$PATH"
#
# USAGE
# -----
#   ./setup-macos-docker.sh                    # uses ~/Desktop/isobyu
#   ISOBYU_DIR=~/software/isobyu ./setup-macos-docker.sh
#
# NOTES ON THE BINARIES
# ---------------------
# The three programs take input in three different ways:
#   findsym  -- keyword input by FILENAME:  findsym input.in
#               (input file must start with !useKeyWords)
#   smodes   -- STDIN only:                 smodes < input.in
#   iso      -- an interactive command shell at a terminal, but it also reads
#               a complete command script from stdin, which is how
#               smodes-phonons drives it -- so it is wrapped with plain -i,
#               no TTY. Type `quit` to exit, not `exit`.
#
# Because $PWD is mounted at /work and the working directory is set to /work,
# filenames passed to these wrappers must be RELATIVE to your current
# directory. Absolute host paths like ~/Desktop/foo.in will not resolve inside
# the container.
#

set -euo pipefail

ISOBYU_DIR="${ISOBYU_DIR:-$HOME/Desktop/isobyu}"
BIN_DIR="${BIN_DIR:-$HOME/.local/bin}"
IMAGE="${IMAGE:-debian:bookworm-slim}"

# Programs that read stdin or a filename -- plain `-i` is correct for these.
# `iso` is included: although it prompts interactively at a real terminal,
# it works fine non-interactively too when given a complete command script
# via stdin (confirmed directly) -- `-i` alone (no pseudo-TTY) is what lets
# a plain `subprocess.run(..., input=...)` call drive it, which `-it` blocks
# with "cannot attach stdin to a TTY-enabled container because stdin is not
# a terminal".
NONINTERACTIVE_PROGS="findsym smodes comsubs findsym_cifinput iso"

# Programs that need a pseudo-TTY because they prompt interactively.
INTERACTIVE_PROGS=""

echo "==> Checking prerequisites"

if ! command -v docker >/dev/null 2>&1; then
    echo "ERROR: docker not found. Install Docker Desktop and try again." >&2
    exit 1
fi

if ! docker info >/dev/null 2>&1; then
    echo "ERROR: Docker is installed but not running. Start Docker Desktop." >&2
    exit 1
fi

ISOBYU_DIR="${ISOBYU_DIR%/}"   # strip any trailing slash for consistency

if [ ! -d "$ISOBYU_DIR" ]; then
    echo "ERROR: isobyu directory not found at: $ISOBYU_DIR" >&2
    echo "       Set ISOBYU_DIR=/path/to/isobyu and re-run." >&2
    exit 1
fi

if [ ! -f "$ISOBYU_DIR/findsym" ]; then
    echo "ERROR: no findsym binary in $ISOBYU_DIR" >&2
    echo "       Did you unzip iso.zip into that directory?" >&2
    exit 1
fi

echo "    docker      OK"
echo "    isobyu      $ISOBYU_DIR"

echo "==> Verifying x86-64 emulation works"
ARCH=$(docker run --platform linux/amd64 --rm "$IMAGE" uname -m 2>/dev/null || true)
if [ "$ARCH" != "x86_64" ]; then
    echo "ERROR: expected x86_64 from emulated container, got: '$ARCH'" >&2
    echo "       Enable Rosetta emulation in Docker Desktop settings." >&2
    exit 1
fi
echo "    emulation   OK (x86_64)"

echo "==> Installing wrappers into $BIN_DIR"
mkdir -p "$BIN_DIR"

write_wrapper() {
    local prog="$1"
    local docker_flags="$2"
    local path="$BIN_DIR/$prog"

    # $prog and $ISOBYU_DIR expand NOW (baked into the script).
    # \$PWD and \$@ are escaped so they expand at RUNTIME.
    cat > "$path" << EOF
#!/bin/bash
# Auto-generated by setup-macos-docker.sh -- do not edit by hand.
# Runs the Linux $prog binary inside a Docker container.
exec docker run --platform linux/amd64 --rm $docker_flags \\
  -v "$ISOBYU_DIR:/isobyu:ro" \\
  -v "\$PWD:/work" -w /work \\
  -e ISODATA=/isobyu/ \\
  $IMAGE /isobyu/$prog "\$@"
EOF
    chmod +x "$path"
    echo "    $prog"
}

for prog in $NONINTERACTIVE_PROGS; do
    if [ -f "$ISOBYU_DIR/$prog" ]; then
        write_wrapper "$prog" "-i"
    else
        echo "    $prog (skipped -- not present in $ISOBYU_DIR)"
    fi
done

for prog in $INTERACTIVE_PROGS; do
    if [ -f "$ISOBYU_DIR/$prog" ]; then
        write_wrapper "$prog" "-it"
    else
        echo "    $prog (skipped -- not present in $ISOBYU_DIR)"
    fi
done

echo "==> Smoke test"
TMPDIR_TEST=$(mktemp -d)
trap 'rm -rf "$TMPDIR_TEST"' EXIT

if [ -f "$ISOBYU_DIR/findsym_sample.in" ]; then
    cp "$ISOBYU_DIR/findsym_sample.in" "$TMPDIR_TEST/"
    if (cd "$TMPDIR_TEST" && "$BIN_DIR/findsym" findsym_sample.in 2>&1 \
        | grep -q "Space Group"); then
        echo "    findsym     OK"
    else
        echo "    findsym     FAILED -- wrapper installed but did not produce output" >&2
    fi
else
    echo "    findsym     skipped (no findsym_sample.in to test with)"
fi

if [ -f "$ISOBYU_DIR/smodes_sample.in" ]; then
    cp "$ISOBYU_DIR/smodes_sample.in" "$TMPDIR_TEST/"
    if (cd "$TMPDIR_TEST" && "$BIN_DIR/smodes" < smodes_sample.in 2>&1 \
        | grep -qi "irrep"); then
        echo "    smodes      OK"
    else
        echo "    smodes      FAILED -- wrapper installed but did not produce output" >&2
    fi
else
    echo "    smodes      skipped (no smodes_sample.in to test with)"
fi

echo
echo "Done. If these commands are not found, add this to ~/.zshrc:"
echo '    export PATH="$HOME/.local/bin:$PATH"'
